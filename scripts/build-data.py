#!/usr/bin/env python3
"""Converts companies.xlsx into app/data.js for the building directory app.

    python3 scripts/build-data.py [companies.xlsx] [app/data.js]

Each sheet is one building; the sheet name (e.g. "building1") is the building
ID that player tags refer to. Row 1 holds the column headers. Custom apps
can't read files at runtime, so the data ships as a script that sets
window.APP_DATA.
"""
import datetime
import json
import re
import sys
from pathlib import Path

try:
    from openpyxl import load_workbook
except ImportError:
    sys.exit("openpyxl is required: pip3 install openpyxl")

ROOT = Path(__file__).resolve().parent.parent
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "companies.xlsx"
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "app" / "data.js"

# Header text (lowercased) -> field name in APP_DATA.
COLUMNS = {
    "company name": "name",
    "company": "name",
    "name": "name",
    "floor": "floor",
    "suite": "suite",
    "category": "category",
    "phone": "phone",
    "website": "website",
    "description": "description",
    "hours": "hours",
    "email": "email",
    "logo": "logo",
}
FIELDS = ["name", "floor", "suite", "category", "phone", "website",
          "description", "hours", "email", "logo"]


def text(value):
    if value is None:
        return ""
    if isinstance(value, float) and value.is_integer():
        value = int(value)
    return str(value).strip()


def building_name(sheet):
    match = re.match(r"^building[\s_-]*(\d+)$", sheet.strip(), re.I)
    if match:
        return "Building " + match.group(1)
    return re.sub(r"[_-]+", " ", sheet.strip()).title()


def read_sheet(ws):
    rows = ws.iter_rows(values_only=True)
    header = next(rows, None) or ()
    fields = {i: COLUMNS[text(h).lower()] for i, h in enumerate(header)
              if text(h).lower() in COLUMNS}
    companies = []
    for row in rows:
        record = dict.fromkeys(FIELDS, "")
        for i, field in fields.items():
            if i < len(row) and not record[field]:
                record[field] = text(row[i])
        if record["name"]:
            companies.append(record)
    return companies


def main():
    if not SRC.exists():
        sys.exit("Not found: %s" % SRC)
    wb = load_workbook(SRC, read_only=True, data_only=True)
    buildings = []
    for ws in wb.worksheets:
        companies = read_sheet(ws)
        buildings.append({
            "id": ws.title.strip().lower(),
            "name": building_name(ws.title),
            "companies": companies,
        })
        print("  %-12s %3d companies" % (ws.title, len(companies)))

    data = {
        "generated": datetime.datetime.now(datetime.timezone.utc)
        .strftime("%Y-%m-%dT%H:%M:%SZ"),
        "buildings": buildings,
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "/* Generated by scripts/build-data.py from companies.xlsx. "
        "Do not edit by hand. */\n"
        "window.APP_DATA = " + json.dumps(data, indent=2, ensure_ascii=True) + ";\n",
        encoding="utf-8",
    )
    print("Wrote %s" % OUT.relative_to(ROOT) if OUT.is_relative_to(ROOT) else OUT)


if __name__ == "__main__":
    main()
